import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const version = JSON.parse(read('manifest.json')).version;
const installUrl = 'https://raw.githubusercontent.com/lumigoh/claude-counter/main/userscript/claude-counter.user.js';
const metadata = `// ==UserScript==
// @name         Claude Counter
// @namespace    https://github.com/she-llac/claude-counter
// @version      ${version}
// @description  Shows token count, cache timer, and session/weekly usage bars on claude.ai.
// @homepageURL  https://github.com/lumigoh/claude-counter
// @downloadURL  ${installUrl}
// @updateURL    ${installUrl}
// @match        https://claude.ai/*
// @run-at       document-start
// @grant        none
// @inject-into  page
// @license      MIT
// ==/UserScript==

// Generated by npm run build:userscript. Edit shared src/ files, then rebuild.
// Tokenizer license notice:
/*
${read('THIRD_PARTY_NOTICES.md').trim()}
*/
`;
const storageAdapter = read('userscript/storage-adapter.js');
const early = ['src/injected/bridge.js', 'src/vendor/o200k_base.js', 'src/content/constants.js', 'src/content/bridge-client.js', 'src/content/tokens.js'];
const browserUI = ['src/content/ui.js', 'src/content/main.js'];
const section = (file) => `\n// Source: ${file}\n${read(file).trim()}\n`;
const output = metadata + `\n(() => {\n'use strict';\n${storageAdapter}\n` + early.map(section).join('') + `
function start() {
	const style = document.createElement('style');
	style.id = 'cc-userscript-styles';
	style.textContent = ${JSON.stringify(read('src/styles.css'))};
	(document.head || document.documentElement).appendChild(style);
${browserUI.map(section).join('')}
}
// Wrap fetch at document-start; mount the UI only after the document exists.
if (document.body) start();
else document.addEventListener('DOMContentLoaded', start, { once: true });
})();
`;
const target = path.join(root, 'userscript/claude-counter.user.js');
if (process.argv.includes('--check')) {
	if (fs.readFileSync(target, 'utf8') !== output) {
		console.error('Userscript is stale. Run npm run build:userscript.');
		process.exitCode = 1;
	} else console.log(`Userscript ${version} matches the shared sources.`);
} else {
	fs.writeFileSync(target, output);
	console.log(`Built userscript ${version} (${Buffer.byteLength(output)} bytes).`);
}
